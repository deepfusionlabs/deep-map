def _rows(rows) -> list:
    return [r for r in (rows or []) if isinstance(r, dict) and "note" not in r]


def _notes(rows) -> list:
    return [str(r["note"]) for r in (rows or []) if isinstance(r, dict) and r.get("note")]


def _match(name, want: str) -> bool:
    """A result name matches `want` exactly or as its last qualified segment ('Class.Member', 'Class#m', 'A::m')."""
    n = str(name or "")
    return n == want or re.split(r"[.#:]+", n)[-1] == want


def check_search(rows, exp) -> tuple:
    """(ok, detail): exp['name'] from exp['file'] among the first SEARCH_TOP results (notes skipped)."""
    top = _rows(rows)[:SEARCH_TOP]
    for i, r in enumerate(top):
        if _match(r.get("name"), exp["name"]) and str(r.get("file") or "").replace("\\", "/").endswith(exp["file"]):
            return True, f"rank {i + 1}: {r.get('name')} {r.get('file')}:{r.get('line')}"
    return False, "top %d: %s" % (SEARCH_TOP, [(r.get("name"), r.get("file")) for r in top])


def check_impact(rows, exp) -> tuple:
    """(ok, detail): every expected caller and every `also` dependent present, each row graded; or, with exp['note'],
    a note containing that text."""
    data = _rows(rows)
    names = [str(r.get("caller") or "") for r in data]
    missing = [c for c in list(exp.get("callers") or []) + list(exp.get("also") or [])
               if not any(_match(n, c) for n in names)]
    ungraded = [r.get("caller") for r in data if not r.get("confidence")]
    problems = []
    if missing:
        problems.append(f"missing {missing}")
    if ungraded:
        problems.append(f"no confidence on {ungraded[:5]}")
    if exp.get("note") and not any(exp["note"] in n for n in _notes(rows)):
        problems.append(f"no note mentioning {exp['note']!r} (notes: {_notes(rows)})")
    detail = "; ".join(problems) if problems else f"{len(data)} dependents, notes {len(_notes(rows))}"
    return not problems, detail


def check_cypher(rows, exp) -> tuple:
    data = _rows(rows)
    if "names" in exp:
        got = sorted(str(r.get("name")) for r in data)
        return got == sorted(exp["names"]), f"rows {got}"
    if "min_n" in exp:
        n = data[0].get("n") if data else None
        return isinstance(n, int) and n >= exp["min_n"], f"n = {n}"
    if "includes" in exp:
        got = {str(r.get("name")) for r in data}
        miss = [x for x in exp["includes"] if x not in got]
        return not miss, f"rows {sorted(got)}" + (f"; missing {miss}" if miss else "")
    return False, "no rule for this expectation"


