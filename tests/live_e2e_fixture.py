def make_project(root, *, git: str = "git") -> dict:
    """write_files + `git init` + one commit, isolated from the machine's git config (no hooks, no signing, no
    autocrlf), with fixed names and dates. {'files': n, 'head': sha or None, 'error': text or None}. An occupied()
    root is refused before anything is written or run there ('error' starts with "refused")."""
    root = Path(root)
    why = occupied(root)
    if why:
        return {"files": 0, "head": None, "error": f"refused: {why}"}
    root.mkdir(parents=True, exist_ok=True)
    files = write_files(root)
    fd, empty_cfg = tempfile.mkstemp(prefix="dm-fixture-gitconfig-")
    os.close(fd)
    env = dict(os.environ, GIT_CONFIG_GLOBAL=empty_cfg, **_GIT_ENV)
    head, error = None, None
    try:
        for args in (["init", "-q"], ["config", "core.autocrlf", "false"], ["config", "commit.gpgsign", "false"],
                     ["add", "-A"], ["commit", "-q", "--no-verify", "-m", "polyshop: initial"]):
            p = subprocess.run([git, "-C", str(root), *args], env=env, capture_output=True, timeout=120)
            if p.returncode != 0:
                error = f"git {' '.join(args)}: {p.stderr.decode('utf-8', 'replace')[-400:]}"
                break
        if error is None:
            p = subprocess.run([git, "-C", str(root), "rev-parse", "HEAD"], env=env, capture_output=True, timeout=60)
            head = p.stdout.decode("utf-8", "replace").strip() or None
    except (OSError, subprocess.SubprocessError) as exc:
        error = repr(exc)
    finally:
        try:
            os.unlink(empty_cfg)
        except OSError:
            pass
    return {"files": len(files), "head": head, "error": error}


