def occupied(root):
    """Why project A must not be written at `root`, or None. It is refused when the path exists and is a file, a
    link or a directory with anything in it: the fixture overwrites README.md, package.json and the sources, sets
    core.autocrlf and commits everything with `git add -A` (a developer's checkout passed by mistake would be
    clobbered and committed). A path that does not exist yet, or an empty directory, is fine."""
    p = Path(root)
    try:
        if not os.path.lexists(p):
            return None
        if p.is_symlink() or not p.is_dir():
            return f"{p} exists and is not a directory"
        if any(p.iterdir()):
            return f"{p} exists and is not empty"
    except OSError as exc:
        return f"{p} cannot be read ({exc})"
    return None


def write_files(root) -> list:
    """Write every file (LF, UTF-8) under root; returns the relative paths, sorted. FileExistsError, before anything
    is written, when root is occupied()."""
    root = Path(root)
    why = occupied(root)
    if why:
        raise FileExistsError(f"refused: {why}")
    for rel, text in FILES.items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(text.encode("utf-8"))
    return sorted(FILES)


def digest(root=None) -> str:
    """sha256 over (path, bytes) of FILES, or of those files as found under root."""
    h = hashlib.sha256()
    for rel in sorted(FILES):
        data = FILES[rel].encode("utf-8") if root is None else (Path(root) / rel).read_bytes()
        h.update(rel.encode("utf-8") + b"\0" + data + b"\0")
    return h.hexdigest()


