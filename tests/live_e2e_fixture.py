_DEF_RX = (re.compile(r"^\s*def (\w+)\(", re.M), re.compile(r"export function (\w+)\("),
           re.compile(r"public [\w<>]+ (\w+)\s*(?:=>|\()"), re.compile(r"(?:public )?(?:async )?Task<\w+> (\w+)\("))


def definitions(src: dict) -> dict:
    """{name: file} of every function / method / property the sources define (first file wins)."""
    out: dict = {}
    for f in sorted(src):
        for rx in _DEF_RX:
            for m in rx.finditer(src[f]):
                out.setdefault(m.group(1), f)
    return out


def body_of(src: dict, name: str) -> str:
    """The text from `name`'s definition to the next top-level definition (enough to see what it calls)."""
    for f in sorted(src):
        text = src[f]
        m = re.search(rf"(?:def|function) {re.escape(name)}\(", text)
        if m:
            nxt = re.search(r"^(?:def |export function |router\.)", text[m.end():], re.M)
            return text[m.start(): m.end() + (nxt.start() if nxt else len(text))]
    return ""


